import { readFile, writeFile, mkdir, cp, rm } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'dist');
let html = await readFile(path.join(root, 'resources/views/home.blade.php'), 'utf8');
const defaults = await readFile(path.join(root, 'resources/views/front/home/expertise-defaults.blade.php'), 'utf8');
html = html.replace(/@if\(\$services->isNotEmpty\(\)\)[\s\S]*?@endif/, defaults);
html = html.replace(/<meta name="csrf-token"[^>]*>/, '');
html = html.replace(/{{\s*asset\('([^']+)'\)\s*}}/g, '$1');
html = html.replace(/{{\s*route\('contact.store'\)\s*}}/g, 'mailto:lionelconcept1@gmail.com');
html = html.replace(/{{\s*old\('[^']+'\)\s*}}/g, '');
html = html.replace(/@csrf/g, '');
html = html.replace(/@if\(\$errors->any\(\)\)[\s\S]*?@endif/, '');
html = html.replace(/@if\(session\('contact_status'\)\)[\s\S]*?@endif/, '');
html = html.replace('data-server="true"', 'data-server="false" enctype="text/plain"');
html = html.replace('Envoyer le message', 'Préparer mon e-mail');
html = html.replace('Votre demande est enregistrée et transmise par e-mail au responsable du site.', 'Cette version ouvre votre messagerie avec un brouillon. Envoyez-le depuis cette application.');
html = html.replace('Ce formulaire fonctionne aussi sans JavaScript.', 'Utilisez le lien e-mail pour me contacter directement.');
if (/{{|@if|@foreach|@include/.test(html)) throw new Error('Unresolved Blade syntax in static export.');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await writeFile(path.join(output, 'index.html'), html);
await writeFile(path.join(output, '.nojekyll'), '');
for (const directory of ['portfolio', 'cv']) await cp(path.join(root, 'public', directory), path.join(output, directory), { recursive: true });
console.log('Static portfolio exported to dist/. Laravel handles server-side submissions; static mode uses email drafts.');
